"""Render the experiment report from committed experiment outputs.

The report is derived, never authored: every figure in it is read from the
JSON files the experiments wrote, so regenerating it cannot disagree with the
measurements. Prose that needs a number quotes metrics.json through the same
anchors the receipts checker guards.
"""

from __future__ import annotations

import json
from pathlib import Path

EXPERIMENTS_DIR = Path(__file__).resolve().parents[2] / "docs" / "experiments"


def _load(experiments_dir: Path, name: str) -> dict:
    return json.loads((experiments_dir / name).read_text(encoding="utf-8"))


def _pct(x: float) -> str:
    return f"{100.0 * x:.1f}%"


def write_report(out: Path, experiments_dir: Path = EXPERIMENTS_DIR) -> None:
    e1 = _load(experiments_dir, "e1_results.json")
    e2 = _load(experiments_dir, "e2_results.json")
    e3 = _load(experiments_dir, "e3_results.json")
    e4 = _load(experiments_dir, "e4_results.json")
    e5 = _load(experiments_dir, "e5_results.json")

    lines: list[str] = []
    add = lines.append
    add("# Experiment report")
    add("")
    add("Generated by `stageattr report` from the committed experiment outputs.")
    add("Regenerate everything with `make experiments && make report`.")
    add("")
    add("## E1: does the attribution method work?")
    add("")
    add("| arm | attribution accuracy | failures judged |")
    add("| --- | --- | --- |")
    for arm in e1["arms"]:
        add(f"| {arm['label']} | {_pct(arm['accuracy'])} | {arm['failures']} |")
    add("")
    add("## E2: the confusable class")
    add("")
    add("| arm | accuracy on tail-ignored | n | 95% CI |")
    add("| --- | --- | --- | --- |")
    for arm in e2["arms"]:
        low, high = arm["ci"]
        add(f"| {arm['label']} | {_pct(arm['accuracy'])} | {arm['n']} | "
            f"{_pct(low)} to {_pct(high)} |")
    add("")
    add("## E3: does improving the retriever help?")
    add("")
    add("| arm | recall at context | end to end accuracy | generation share of failures |")
    add("| --- | --- | --- | --- |")
    for arm in e3["arms"]:
        add(f"| {arm['label']} | {_pct(arm['recall_at_ctx'])} | {_pct(arm['e2e_accuracy'])} | "
            f"{_pct(arm['generation_share'])} |")
    add("")
    add(f"Recall gained {e3['recall_gain_pp']:.1f} points; end to end accuracy gained "
        f"{e3['e2e_gain_pp']:.1f} points.")
    add("")
    add("## E4: does chunking move the blame?")
    add("")
    add("| strategy | chunks | retrieval_miss | retrieval_rank | generation |")
    add("| --- | --- | --- | --- | --- |")
    for arm in e4["arms"]:
        mix = arm["truth_mix"]
        add(f"| {arm['strategy']} | {arm['chunks']} | {_pct(mix['retrieval_miss'])} | "
            f"{_pct(mix['retrieval_rank'])} | {_pct(mix['generation'])} |")
    add("")
    add("## E5: what node instrumentation costs")
    add("")
    add(f"Trace size: {e5['trace_records_per_question']} records and "
        f"{e5['trace_bytes_per_question_median']} bytes per question (median). "
        "The wall time overhead ratio lives in docs/metrics.json and is asserted by a test "
        "rather than quoted here, because a duration is a fact about the runner.")
    add("")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
